#!/usr/bin/env node
/**
 * Vendor the spaces lexicons from a checkout of bluesky-social/atproto.
 *
 *   node scripts/vendor-lexicons.mjs <path-to-atproto-checkout>
 *
 * Copies every lexicon under `lexicons/com/atproto/{NAMESPACES}` verbatim
 * into `lexicons/`, removes namespaces that no longer exist upstream,
 * regenerates `src/lexicons.ts` (explicit imports, so bundlers carry the
 * documents without filesystem access at runtime) and stamps
 * `lexicons/MANIFEST.json` with the source commit.
 *
 * Check out the commit the pinned alpha build was cut from before running.
 * A diff in `lexicons/` then identifies affected checks via their citations,
 * and the coverage test names any method or error that has no MUST check.
 */

import { execFileSync } from "node:child_process";
import {
	cpSync,
	existsSync,
	mkdirSync,
	readdirSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** Namespaces under com.atproto that make up the spaces protocol. */
const NAMESPACES = ["space", "memberspace", "personalspace", "managedspace"];

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2];
if (!source) {
	console.error("usage: vendor-lexicons.mjs <path-to-atproto-checkout>");
	process.exit(1);
}

const git = (...args) =>
	execFileSync("git", ["-C", source, ...args], { encoding: "utf8" }).trim();
const commit = git("rev-parse", "--short=9", "HEAD");
const branch = git("rev-parse", "--abbrev-ref", "HEAD");

const target = join(root, "lexicons");
for (const entry of readdirSync(target, { withFileTypes: true })) {
	if (entry.isDirectory()) rmSync(join(target, entry.name), { recursive: true });
}

const imports = [];
const names = [];
for (const ns of NAMESPACES) {
	const from = join(source, "lexicons", "com", "atproto", ns);
	if (!existsSync(from)) {
		throw new Error(`Missing upstream namespace: com.atproto.${ns}`);
	}
	mkdirSync(join(target, ns), { recursive: true });
	for (const file of readdirSync(from).filter((f) => f.endsWith(".json")).sort()) {
		cpSync(join(from, file), join(target, ns, file));
		const name = `${ns}_${file.replace(/\.json$/, "")}`;
		imports.push(
			`import ${name} from "../lexicons/${ns}/${file}" with { type: "json" };`,
		);
		names.push(name);
	}
}

writeFileSync(
	join(root, "src", "lexicons.ts"),
	`/**
 * Vendored lexicon access. Generated by scripts/vendor-lexicons.mjs whenever
 * lexicons/ is re-vendored — imports are explicit so bundlers carry the
 * documents without filesystem access at runtime.
 */

${imports.join("\n")}

export interface LexiconDoc {
	lexicon: number;
	id: string;
	defs: Record<string, unknown>;
}

export const lexicons: LexiconDoc[] = [
${names.map((name) => `\t${name} as LexiconDoc,`).join("\n")}
];
`,
);

writeFileSync(
	join(target, "MANIFEST.json"),
	`${JSON.stringify(
		{
			source: "https://github.com/bluesky-social/atproto",
			branch,
			commit,
			vendoredAt: new Date().toISOString().slice(0, 10),
			note: `Vendored verbatim from lexicons/com/atproto/{${NAMESPACES.join(",")}} by scripts/vendor-lexicons.mjs. A diff here identifies affected checks via their citations.`,
		},
		null,
		"\t",
	)}\n`,
);

console.log(`Vendored ${names.length} lexicons from ${branch}@${commit}`);
